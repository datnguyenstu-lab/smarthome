// Languages: English (the source text) and Vietnamese. The English text is the key: t('Settings') returns it
// as is in English and the Vietnamese version below in Vietnamese. {name} placeholders are filled from `vars`.
// A text with no Vietnamese entry is shown in English, never blank.

let lang = 'en';

export function getLang() { return lang; }
export function setLang(l) { lang = l === 'vi' ? 'vi' : 'en'; return lang; }

// A saved choice wins; otherwise the browser's language (vi-VN, vi, ...); otherwise English.
export function detectLang(stored, browserLang) {
  if (stored === 'en' || stored === 'vi') return stored;
  return /^vi(\b|-)/i.test(browserLang || '') ? 'vi' : 'en';
}

export function t(text, vars) {
  const s = lang === 'vi' && Object.prototype.hasOwnProperty.call(VI, text) ? VI[text] : text;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

